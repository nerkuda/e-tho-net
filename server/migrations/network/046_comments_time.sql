-- 046: время хроно-записей (0.10.1, задача T1 62a0a604; требования
-- «Формат дат хроно-записи» d58aa1a4, «Флаг "учитывать время"» 91ba5b3f,
-- «Миграция дат хроники» 4c316b45; ADR 994d076a; сущность comments f009d46e).
--
-- Что делает эта миграция (схема + данные, без доменной логики — её ведёт T2):
--
--   1. Добавляет булев столбец `use_time` («учитывать время») — NOT NULL,
--      DEFAULT 0. Флаг хранится на записи и управляет только показом/правкой
--      времени в клиенте; на формат `valid_from`/`valid_to` он не влияет.
--   2. Приводит даты хроно-записей к полным UTC-инстансам ISO-8601 с мс:
--      «голая дата» `YYYY-MM-DD` превращается в `YYYY-MM-DDT00:00:01.000Z` —
--      маркер «время при миграции не задавалось». Значения с временем не
--      трогаем (домен и раньше писал их как `toISOString()` с мс).
--   3. Заполняет пустое окончание хронологической записи её началом —
--      инвариант «`valid_to` у хронологической не пусто (не заполнено =
--      `valid_from`)». У постоянного комментария `valid_to` остаётся `NULL`.
--
-- Почему даты «голой датой». До 0.10.1 домен хранил `valid_from` как есть:
-- `2024-01-01` оставался `2024-01-01` (comment-service `normaliseDate`), а
-- `valid_to` у хронологической мог быть `NULL` («бессрочно»). Дневнику нужен
-- единый полный инстанс: сервер не придаёт датам смысла «календарного дня» и
-- не конвертирует часовые пояса — день принадлежности считает клиент в поясе
-- наблюдателя. «Голая дата» во входных параметрах = сутки UTC (ADR 994d076a).
--
-- Идемпотентность ПРИВЕДЕНИЯ ДАННЫХ: после конвертации строка перестаёт
-- совпадать с 10-символьным GLOB-шаблоном даты, а `valid_to IS NULL` у
-- хронологической после заполнения ложно, — повторный прогон UPDATE-ов
-- (шаги 2–3) не меняет данные. `ALTER TABLE ADD COLUMN` (шаг 1) идемпотентным
-- не является и повторно не выполняется: мигратор помнит применённый файл.
--
-- Граница с задачей T2 (`fca5b507`): валидацию входа на запись (запрет
-- date-only и пустого `valid_to` с понятной ошибкой) делает домен — здесь
-- только схема и приведение уже накопленных данных.

-- ---------------------------------------------------------------------------
-- 1. Флаг «учитывать время» (по умолчанию выключен — у новых записей тоже)
-- ---------------------------------------------------------------------------

ALTER TABLE comments ADD COLUMN use_time INTEGER NOT NULL DEFAULT 0;

-- ---------------------------------------------------------------------------
-- 2. date-only → полный UTC-инстанс (маркер 00:00:01.000Z)
-- ---------------------------------------------------------------------------

UPDATE comments
   SET valid_from = valid_from || 'T00:00:01.000Z'
 WHERE valid_from GLOB '[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]';

UPDATE comments
   SET valid_to = valid_to || 'T00:00:01.000Z'
 WHERE valid_to GLOB '[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]';

-- ---------------------------------------------------------------------------
-- 3. Пустое окончание хронологической = началу (постоянный остаётся NULL)
-- ---------------------------------------------------------------------------

UPDATE comments
   SET valid_to = valid_from
 WHERE kind = 'chronological' AND valid_to IS NULL;
