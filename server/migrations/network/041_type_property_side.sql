-- 041: сторона привязки свойства-связи — колонка `type_properties.side`
-- (0.8.1, задача e1fbf304 «Сервер: сторона привязки и единый жизненный цикл
-- свойства-связи»; требования b9562306 «Свойство-связь одно на тип связи;
-- сторона задана привязкой», 115e44fa «Привязка со стороны назначения
-- равноправна с привязкой источника»).
--
-- Что делает миграция (одним файлом = одной транзакцией мигратора, по
-- каждой сети инстанса):
--
--   1. добавляет в `type_properties` колонку `side TEXT` — `source` для
--      привязки со стороны источника, `target` для стороны назначения,
--      `NULL` для скалярных и структурных свойств-связей;
--   2. материализует `side` для существующих ЖИВЫХ привязок свойств-связей
--      по `config.direction` (миграция 040 оставила `direction: 'out' |
--      'in'` в реестре; встречные свойства, появившиеся до 0.8.1, дают
--      разные `side` — это нормально, миграция данных сетей f7633481
--      превратит их в одну строку реестра);
--   3. оставляет структурные «Родители» / «Потомки» с `side = NULL`
--      (направление у них — атрибут реестровой строки `config.direction`,
--      а не привязки; требование 39a76760).
--
-- СЛОИ. Запись идёт по ВСЕМ строкам `type_properties` всех слоёв. Значение
-- `side` детерминировано значением `config.direction` той же физической
-- строки — теневое правило «shadow-копия наследует все поля» даёт тот же
-- результат, что и заполнение из основы; после миграции в живой сети не
-- остаётся привязок link-свойства с пустым `side`. Слияние рабочего слоя
-- после миграции безопасно (теневая копия коллапсирует на равную тройку
-- основы).
--
-- ЗЕРКАЛА (требование 115e44fa) не материализуются здесь — это предмет
-- отдельной миграции данных f7633481 «Сервер: миграция единого реестра
-- свойств и связей», которая превратит встречные свойства в одно и
-- построит настоящие привязки со стороны назначения. На момент этой
-- миграции существующая модель (привязка с `direction: 'in'` у каждого
-- встречного свойства) сохраняет семантику: считается, что у одного
-- link_type может быть две привязки с разными направлениями у двух
-- разных типов мысли.
--
-- НЕОБРАТИМО: отката нет (добавление колонки без потери данных). Перед
-- обновлением рекомендуется резервная копия data.db сети
-- (docs/install-server.md, CHANGELOG).

-- ---------------------------------------------------------------------------
-- 1. Колонка side. CHECK страхует от опечаток: `source` / `target` / NULL.
-- ---------------------------------------------------------------------------

ALTER TABLE type_properties ADD COLUMN side TEXT
  CHECK (side IS NULL OR side IN ('source', 'target'));

-- ---------------------------------------------------------------------------
-- 2. Материализация side для существующих живых привязок link-свойств.
--    direction берётся из config строки реестра (JSON). Структурные
--    свойства (`config.structural = true`) и скаляры остаются с side=NULL.
--    Встречные свойства на один link_type получают разные side — это
--    промежуточное состояние до миграции данных f7633481.
-- ---------------------------------------------------------------------------

UPDATE type_properties AS tp
   SET side = CASE
                WHEN json_extract(p.config, '$.structural') = 1
                  OR p.value_type <> 'link'
                THEN NULL
                WHEN json_extract(p.config, '$.direction') = 'in' THEN 'target'
                WHEN json_extract(p.config, '$.direction') = 'out' THEN 'source'
                ELSE NULL
              END
  FROM properties AS p
 WHERE p.id = tp.property_id
   AND tp.deleted = 0
   AND p.deleted = 0
   AND tp.side IS NULL;

-- ---------------------------------------------------------------------------
-- 3. Дозаполнение side в теневых копиях рабочих слоёв: значение теневой
--    копии = значение физической строки основы для той же привязки. Это
--    согласует видимость по цепочке слоёв — иначе в слое, где создана
--    теневая копия, `side` будет NULL, а направление вычислится через
--    config.direction (тот же результат, но разными путями; унификация
--    исключает сюрпризы).
-- ---------------------------------------------------------------------------

UPDATE type_properties AS child
   SET side = (
        SELECT base.side
          FROM type_properties AS base
         WHERE base.id = child.id
           AND base.layer_id = '00000000-0000-4000-8000-0000000000ba5e'
           AND base.deleted = 0
       )
 WHERE child.deleted = 0
   AND child.side IS NULL;
