-- Цвет символа иконки мысли и типа мысли (0.12.1, задача 4105bd6a).
--
-- `icon_color` — необязательный HEX-цвет (`#rrggbb`) ЗНАЧКА иконки, независимый
-- от `fg_color` (цвет текста) и `bg_color` (фон облачка). Пусто (`NULL`) —
-- прежнее поведение: библиотечный значок рисуется `currentColor` и наследует
-- цвет текста, эмодзи/картинка цвет не применяют. Поле есть и у мысли, и у
-- типа мысли; значение наследуется по цепочке типов ВМЕСТЕ с иконкой (LEVEL-21,
-- требование 0da6f02a): собственная иконка мысли берёт свой цвет, унаследованная
-- от типа — цвет того типа, что дал иконку. Валидация значения — на сервере
-- (REST-контракты и домен отвергают не-HEX с VALIDATION_ERROR).
--
-- Plain ADD COLUMN безопасен и транзакционен; мигратор не перезапускает файл,
-- поэтому IF NOT EXISTS не нужен (та же оговорка, что у миграций 013/015/016).

ALTER TABLE thoughts ADD COLUMN icon_color TEXT;
ALTER TABLE thought_types ADD COLUMN icon_color TEXT;
