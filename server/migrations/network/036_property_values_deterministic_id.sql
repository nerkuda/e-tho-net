-- 036: property_values — детерминированные id от natural key
-- (ошибка dc119240 «Чтение значений свойств может показать дубликат/устаревшее
-- значение на пересечении слоёв», версия 0.7.2; вариант 2 из карточки ошибки,
-- одобрен пользователем).
--
-- Корень. Логическая идентичность строки property_values — естественный ключ
-- (owner_type, owner_id, property_id), а не столбец id. Представления слоёв
-- *_v (layer-chain.ts ensureLayerViews) применяют «ближайший слой побеждает»
-- ПО id: если для одного natural key независимо (в не видящих друг друга
-- слоях — дочерний слой, затем основа) заведены ДВА разных случайных id, обе
-- строки остаются «видимыми победителями» одновременно → чтения отдают
-- дубль/призрак, удаление из дочернего слоя оставляет всплывающий дальний
-- дубль (UNIQUE (owner_type, owner_id, property_id, layer_id) не даёт создать
-- вторую строку того же ключа в слое, чтобы её перекрыть).
--
-- Решение. id строки становится детерминированным от natural key:
-- UUIDv5(namespace, owner_type || ':' || owner_id || ':' || property_id) —
-- вычисляется SQL-функцией etn_pv_id, зарегистрированной в
-- registerMigrationHelpers (db/network-db.ts) поверх того же TypeScript-кода,
-- что использует доменный путь записи (db/property-value-id.ts). Миграция и
-- рантайм не могут разойтись в вычисленном id. Независимые «первые записи»
-- разных слоёв сходятся в один id, и вся по-id инфраструктура (*_v,
-- materializeShadow) становится корректной без правки потребителей.
--
-- Почему построчный UPDATE безопасен:
--   * UNIQUE (owner_type, owner_id, property_id, layer_id) (миграция 025)
--     гарантирует максимум ОДНУ строку natural key на слой — после сведения
--     в слое не может оказаться двух строк с одним id, UNIQUE (id, layer_id)
--     не нарушается. Битые данные («две строки одного natural key в одном
--     слое») невозможны: ограничение существует с создания таблицы.
--   * Строки разных natural key получают разные SHA-1-хеши (коллизия
--     практически исключена); теневые копии и надгробия того же logical row
--     несут тот же natural key и сходятся в тот же id в своём слое.
--   * На property_values нет SQL-FK и его id никто не ссылается (комментарии
--     и вложения вешаются только на мысли/связи; журнал активности пишет
--     entity_id только сущностей справочника properties) — переименование id
--     ничего не рвёт.
--
-- WHERE-фильтр делает повторное применение идемпотентным (мирратор не
-- перезапускает записанный файл, но прямое переисполнение оператора — no-op).
--
-- Схема таблицы не меняется: детерминированный id — это данные, не DDL.

UPDATE property_values
SET id = etn_pv_id(owner_type, owner_id, property_id)
WHERE id != etn_pv_id(owner_type, owner_id, property_id);
