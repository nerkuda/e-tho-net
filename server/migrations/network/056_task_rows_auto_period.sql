-- 056_task_rows_auto_period.sql - автопериод и автосубъекты задач (0.16.1,
-- задача 1f516872; уточнение ТЗ 2026-11-16).
--
-- Задача строки БЕЗ date-ссылок в хроно-записи получает период записи
-- (`valid_from..valid_to` владельца-комментария целиком): срок — конец периода.
-- Дата в строке приоритетнее: есть хотя бы одна date-ссылка - период из неё.
--
-- `auto_period = 1` помечает такую строку: по признаку PATCH /tasks различает
--   * `undate` («Сделать бессрочной») для строк хроно-записи - 400: автопериод
--     вернул бы дату при пере-парсинге, команда бессмысленна;
--   * `set_due`/`move` для авто-строки дописывают явную date-ссылку `[[дата]]` -
--     задача закрепляется и перестаёт зависеть от периода записи.
--
-- Автосубъекты (владелец постоянного комментария - мысль или оба конца связи)
-- живут в `task_row_subjects`; отдельной колонки не требуют, но их состав
-- меняется, поэтому старые строки тоже надо пере-собрать.
--
-- Пере-сбор идёт свипом проекции при старте сервера (`TASK_PROJECTION_VERSION`
-- поднят), а свип перестраивает только сети с маркером 0. Поэтому миграция
-- сбрасывает маркер: иначе существующие строки остались бы без автопериода и
-- автосубъектов до ручного «Обновить», и «Просрочено» не пополнилось бы
-- задачами прошлых записей (следствие, принятое пользователем).

ALTER TABLE task_rows ADD COLUMN auto_period INTEGER NOT NULL DEFAULT 0;

UPDATE task_projection_state SET max_revision = 0;
