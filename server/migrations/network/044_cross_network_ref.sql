-- 044: кросс-сетевая ссылка как отдельный вид значения свойства
-- (0.8.3, задача 7849008a, ADR ae8346d0, требования 884d14e1/aa89940c/6d4ad9ac/95511443/c104a0fc/586ebe81/717ca2cb/eb1c4e82).
--
-- Новый `value_type = 'cross_network_ref'` в реестре `properties`. Значение
-- хранится в `property_values.value_text` как скаляр — адрес
-- `n:<network_id>#<thought_id>` (single) или JSON-массив адресов (multiple,
-- `config.multiple = true`). Цель — всегда в ДРУГОЙ сети; на свою сеть
-- валидация записи отвечает `VALIDATION_ERROR` (см. требование 884d14e1).
--
-- Рядом с каждой записью значения живёт служебный НАБОР СНАПШОТОВ имени цели
-- (`title_snapshot`, `resolved_at`, `unresolved`) в таблице
-- `property_value_cross_refs`. Снапшот — кэш имени, не содержательная правка:
-- обновление НЕ создаёт слойных теневых строк, НЕ расходует write-бюджет и
-- НЕ пишется в `audit_log` (требование c104a0fc). Снапшоты живут в
-- НЕВЕТВИМОЙ таблице (нет `layer_id`, не копируются при shadow): каждый
-- слой видит текущее имя цели, не загрязняя видимость значений.
--
-- Снапшот заполняется ОДИН РАЗ при записи значения (живой резолв, требование
-- aa89940c) и обновляется по ДЕЙСТВИЮ: REST cross-resolve, MCP
-- `etn.properties.resolve`, переход по ссылке в клиенте, команда контекстного
-- меню (требование 95511443). При сбое (сеть или цель удалены / нет прав)
-- снапшот сохраняется, `unresolved = 1` — пользователь продолжает видеть
-- имя цели, флаг нерезолвленности бросается в глаза (требование 6d4ad9ac).
--
-- Обратной стороной ссылки служит сама запись значения: кросс-сетевое
-- значение не участвует в `meta.link_stats`, не рисуется на карте, не
-- попадает в `backlinks`/`mentions`/`usage` (требование eb1c4e82) — никаких
-- рёбер или индексов между сетями мы не вводим.
--
-- ДЕЙСТВИЯ МИГРАЦИИ (по каждой сети инстанса):
--
--   1. Создаём неветвимую таблицу `property_value_cross_refs` с привязкой
--      к ФИЗИЧЕСКОМУ `property_values.id` (НЕ логическому — у одного
--      значения в разных слоях может быть разный id после shadow-копии).
--      Снапшоты живут в той же строке, что и значение (один JSON на запись
--      значения — это и single, и multiple; снапшоты массива лежат в нём
--      же).
--   2. Включаем `cross_network_ref` в `PROPERTY_VALUE_TYPES` на уровне
--      приложения (миграцией не делаем — тип в общем `enums.ts` @etn/shared;
--      мигратор СУБД-уровень не трогает).
--   3. Индекс на `property_value_id` — единственный «рабочий» индекс; всё
--      остальное — поиск по первичному ключу.
--
-- НЕОБРАТИМОСТЬ: миграция только добавляет служебную таблицу и не трогает
-- существующие строки `property_values`. Удаление миграции (откат) на боевой
-- базе потребует удаления `property_value_cross_refs` ПОСЛЕ очистки всех
-- значений `cross_network_ref` (если такие есть в БД).

-- ---------------------------------------------------------------------------
-- 1. Служебная неветвимая таблица снапшотов
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS property_value_cross_refs (
  property_value_id TEXT NOT NULL,        -- физический id строки property_values
  -- JSON: { items: [{ network_id, thought_id, title, resolved_at, unresolved }] }
  -- Для single — массив всегда длины 1; адрес живёт в property_values.value_text.
  -- Для multiple — массив параллелен JSON-массиву адресов в value_text.
  -- `unresolved: 1` означает «последний живой резолв отказал»;
  -- `title` при этом всё равно сохранён (имя остаётся видимым из снапшота).
  payload         TEXT NOT NULL,
  updated_at      TEXT NOT NULL,
  updated_at_ms   INTEGER NOT NULL,
  PRIMARY KEY (property_value_id)
);

-- Быстрый поиск снапшота по физическому id значения (основной путь чтения
-- карточки мысли/связи). FK на property_values.id сознательно НЕ ставим:
-- снапшот — служебные данные, удаляются каскадом по id вместе с владельцем
-- на уровне приложения (см. server-side property-service.ts).

CREATE INDEX IF NOT EXISTS idx_pv_cross_refs_value
  ON property_value_cross_refs (property_value_id);
