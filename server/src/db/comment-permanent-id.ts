/**
 * Детерминированные id постоянного комментария (ошибка 46b93145, версия 0.12.1).
 *
 * Логическая идентичность постоянного комментария — его владелец
 * `(owner_type, owner_id)`, а не суррогатный `id`. Представления слоёв `*_v`
 * (db/layer-chain.ts) дедуплицируют «ближайший слой побеждает» ПО `id`,
 * поэтому две независимые «первые записи» постоянного комментария одного
 * владельца в не видящих друг друга слоях (дочерний слой, затем основа) с
 * РАЗНЫМИ случайными id рождают двух «видимых победителей» на один natural
 * key: в контексте слоя `comments_v` отдаёт ДВА постоянных комментария —
 * частичный индекс `idx_comments_permanent_one` и проверка дубля в
 * `createCommentWithTargets` действуют лишь В ПРЕДЕЛАХ одного слоя
 * (`owner_type, owner_id, layer_id`), кросс-слойной уникальности нет.
 *
 * Решение (по образцу `property_values`, ошибка dc119240 / миграция 036): id
 * постоянного комментария выводится детерминированно из natural key как
 * UUIDv5 (RFC 4122) от строки `${owner_type}:${owner_id}` в фиксированном
 * namespace. Независимые первые записи разных слоёв всегда сходятся в ОДИН
 * id, и вся существующая по-id инфраструктура (`comments_v`,
 * `getPermanentRow`, copy-on-write `materializeShadow`) корректна без
 * переписывания потребителей: для логического id побеждает ближайший слой
 * цепочки (13-layers.md §4.1) — ровно один видимый постоянный комментарий на
 * контекст.
 *
 * Формат обязан оставаться валидным UUID (TEXT-колонка, клиенты парсят его
 * как UUID), поэтому используется именно UUIDv5, а не «сырой» хеш.
 */

import { uuidV5 } from './uuid-v5.js';

/**
 * Фиксированный namespace UUIDv5 для постоянных комментариев. Никогда не
 * менять: смена namespace молча сменит id всех существующих строк и снова
 * разведёт слои.
 */
export const PERMANENT_COMMENT_ID_NAMESPACE = '788582f8-be25-46d7-b54b-13df104b17f3';

/**
 * Детерминированный id постоянного комментария от его natural key:
 * UUIDv5(PERMANENT_COMMENT_ID_NAMESPACE, `${owner_type}:${owner_id}`).
 *
 * Разделитель `:` безопасен: `owner_type` — закрытый список
 * ('thought'|'link') без двоеточий, `owner_id` — UUID.
 */
export function permanentCommentId(ownerType: string, ownerId: string): string {
  return uuidV5(PERMANENT_COMMENT_ID_NAMESPACE, `${ownerType}:${ownerId}`);
}
