/**
 * Чистое ядро фокусировки постоянного комментария (задача ea1b5f14, блокер 4
 * верификации): какой следующий шаг делает ожидание поля комментария.
 *
 * Вынесено из `editor.ts` ради тестируемости: холодная смена мысли в редакторе
 * асинхронна — панель держит ПРЕДЫДУЩУЮ сущность, пока грузится новая. Если
 * действовать по одному факту «поле `.md-field` существует», правка включается
 * у СТАРОЙ мысли, а поле целевой монтируется уже в режиме просмотра. Поэтому
 * шаг ожидания обязан сверять ВЛАДЕЛЬЦА отрендеренной панели с запрошенной
 * мыслью, а активацию вкладки/группы делать до постановки каретки.
 */

/** Что делать дальше: ждать, активировать вкладку/группу или ставить каретку. */
export type CommentFocusStep = 'wait' | 'activate' | 'focus';

/** Вход шага ожидания. */
export interface CommentFocusState {
  /** id мысли, реально отрисованной в панели (`renderCtx.ownerId`); `null` — не мысль. */
  renderedOwnerId: string | null;
  /** id запрошенной мысли. */
  thoughtId: string;
  /** Поле `.md-field` нужной панели существует и подключено. */
  hasField: boolean;
  /** Вкладка «Комментарий»/группа уже активированы в этом цикле. */
  activated: boolean;
}

/**
 * Шаг ожидания. Владелец панели не совпал с запрошенной мыслью — ждём, даже
 * если поле существует (это поле старой мысли). Далее АКТИВИРУЕМ вкладку
 * «Комментарий» — поле появляется только после этого, поэтому проверять его
 * наличие до активации нельзя: иначе при открытой вкладке «Свойства» шаг
 * навсегда застревал в `wait` и вкладка не переключалась (задача 77cce0ba, п.3).
 * Когда вкладка активирована и поле смонтировано — ставим каретку.
 */
export function commentFocusStep(state: CommentFocusState): CommentFocusStep {
  if (state.renderedOwnerId !== state.thoughtId) return 'wait';
  if (!state.activated) return 'activate';
  if (!state.hasField) return 'wait';
  return 'focus';
}
