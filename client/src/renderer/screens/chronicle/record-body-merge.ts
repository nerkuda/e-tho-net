/**
 * Построчное слияние черновика открытой правки записи с внешней правкой
 * источника (0.16.1, задача `b36a3d49`, блокер репроверки `90c35105`).
 *
 * **Зачем.** Пока правка записи открыта, источник может измениться под ней:
 * «Отменить задачу» из панели снимает маркер строки, чекбокс просмотра меняет
 * соседнюю строку. Черновик обновлялся только когда пользователь ничего не
 * набрал: набравший текст держал устаревший документ, и `Ctrl+Enter` возвращал
 * в источник отменённую строку. Теперь правки источника применяются построчно —
 * строки, которых пользователь не касался, берутся из свежего тела.
 *
 * **Правила.**
 *  • база сравнения — последний известный серверный текст (`knownMd`);
 *  • правок пользователя нет (`userMd === knownMd`) — берём источник целиком;
 *  • правок источника нет (`serverMd === knownMd`) — оставляем черновик;
 *  • разошлось ЧИСЛО строк (их добавили или удалили) — `null`: документ не
 *    трогаем. Выравнивание разной длины — уже не «строка задачи», а переписанный
 *    текст, где угадывание дороже потери ввода;
 *  • одна и та же строка изменена обеими сторонами — приоритет ПОЛЬЗОВАТЕЛЯ
 *    (осознанный размен: молча потерять набранное хуже, чем вернуть одну
 *    серверную правку в этой строке);
 *  • обе стороны написали в ПУСТУЮ строку (запись была пуста, пользователь начал
 *    печатать, панель добавила строку задачи) — `null`: не выбирать, чей текст
 *    выбросить, из двух вариантов (документ остаётся как есть).
 *
 * **Почему отдельный модуль.** Экран `chronicle.ts` под Node не поднимается
 * (нужен Electron-каркас), а правило слияния — чистая функция: проверяется без
 * DOM и сети (`tests/record-body-merge.test.ts`).
 */

/**
 * Слить черновик правки с внешним телом записи построчно.
 *
 * @param knownMd последний известный серверный `body_md` (база сравнения)
 * @param userMd  текущий текст поля правки
 * @param serverMd свежий `body_md` источника
 * @returns текст для поля правки либо `null`, если сливать нечего безопасно
 *          (разошлось число строк) — тогда документ остаётся как есть
 */
export function mergeRecordBody(knownMd: string, userMd: string, serverMd: string): string | null {
  if (serverMd === knownMd) return userMd;
  if (userMd === knownMd) return serverMd;
  const known = knownMd.split('\n');
  const user = userMd.split('\n');
  const server = serverMd.split('\n');
  if (user.length !== known.length || server.length !== known.length) return null;
  const merged: string[] = [];
  for (let i = 0; i < known.length; i += 1) {
    const base = known[i] ?? '';
    const mine = user[i] ?? base;
    const theirs = server[i] ?? base;
    if (mine === base) {
      // Строку пользователь не трогал — берём серверную редакцию (с её правкой
      // или без).
      merged.push(theirs);
      continue;
    }
    // Обе стороны писали в пустую строку: чей текст выбрасывать — не решаем.
    if (base === '' && theirs !== base) return null;
    merged.push(mine);
  }
  return merged.join('\n');
}
