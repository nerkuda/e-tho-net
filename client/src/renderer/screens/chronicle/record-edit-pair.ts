/**
 * Пара «заголовок ↔ тело» единой правки дневниковой записи: кто кого открывает
 * и кому принадлежит фокус (0.16.1, блокер вердикта `84c71c37` по `cfb8cb72`).
 *
 * **Правило.** Заголовок и тело правятся вместе, но фокус остаётся там, откуда
 * начался вход:
 *  • вход в ТЕЛО (двойной клик по телу, «Открыть источник» строки задачи) —
 *    заголовок присоединяется к правке БЕЗ фокуса;
 *  • вход в ЗАГОЛОВОК (двойной клик по нему) — тело открывается, фокус остаётся
 *    в заголовке.
 *
 * **Почему отдельный модуль.** Экран `chronicle.ts` под Node не поднимается
 * (нужен Electron-каркас), а правило фокуса проверяемо без DOM и сети: здесь
 * только последовательность действий, экран передаёт их реализацию.
 *
 * **Что было не так.** Заголовок открывался программно вместе с телом и тут же
 * звал хозяина «войти в правку заголовка» — тот асинхронно (после дочитывания
 * тела) ставил фокус в `INPUT` заголовка уже ПОСЛЕ фокуса строки задачи:
 * каретка уезжала из `.cm-content`, а `Esc` и клик вне переставали закрывать
 * правку — клавиатура принадлежала полю, которого нет в фокусе.
 */

/** Действия экрана, которыми правит пара «заголовок ↔ тело». */
export interface RecordEditPairActions {
  /** Тело уже в правке (состояние последнего `onEditChange`). */
  bodyEditing(): boolean;
  /** Заголовок сейчас в правке. */
  titleEditing(): boolean;
  /** Открыть заголовок БЕЗ фокуса (он присоединяется к правке тела). */
  openTitle(): void;
  /** Вернуть заголовок в просмотр без фокуса (выход из правки). */
  closeTitle(): void;
  /** Войти в единую правку записи способом экрана (со своим фокусом). */
  enterBodyEdit(): void;
  /** Вернуть фокус в навигацию ленты (после выхода из правки). */
  focusFeedNavigation(): void;
}

export const recordEditPair = {
  /**
   * `onEditChange` тела: заголовок присоединяется к правке, если ещё не открыт,
   * и закрывается вместе с ней. Фокус при этом не переставляется — им владеет
   * то поле, куда вошёл пользователь (или навигация ленты после выхода).
   */
  bodyChanged(actions: RecordEditPairActions, isEdit: boolean): void {
    if (isEdit) {
      if (!actions.titleEditing()) actions.openTitle();
      return;
    }
    if (actions.titleEditing()) actions.closeTitle();
    actions.focusFeedNavigation();
  },
  /**
   * `onBeginEdit` заголовка: тело открывается, ТОЛЬКО когда вход начался с
   * заголовка. Тело уже в правке — заголовок лишь присоединился, фокус не
   * перебиваем (блокер `84c71c37`).
   */
  titleBegan(actions: RecordEditPairActions): void {
    if (actions.bodyEditing()) return;
    actions.enterBodyEdit();
  },
} as const;

/** Запросить следующий кадр отрисовки; вне браузера — выполнить сразу. */
function requestFrame(callback: () => void): void {
  if (typeof requestAnimationFrame === 'function') {
    requestAnimationFrame(callback);
    return;
  }
  callback();
}

/**
 * Поставить ленту «Дневника» в самый верх и УДЕРЖАТЬ её там после отложенной
 * прокрутки правки (блокер Б2-Н репроверки `4b755c93` по задаче `cfb8cb72`).
 *
 * **Что было не так.** «Открыть источник» ждал `editLine`, но промис
 * завершается на установке каретки: CodeMirror прокручивает поле к каретке
 * отдельным кадром (`scrollIntoView`), уже ПОСЛЕ промиса, и сдвигал ленту на
 * 111px (`cardTopInWrap -18`). Одиночное `scrollTop = 0` после `await` этот
 * кадр не переживало.
 *
 * **Правило.** Ставим верх сразу и повторяем в двух следующих кадрах: первый
 * перекрывает прокрутку CM текущего кадра, второй — её возможную вторую волну
 * (измерение после отрисовки). `schedule` — точка подмены в тесте.
 */
export function pinFeedTop(
  setScrollTop: (top: number) => void,
  schedule: (callback: () => void) => void = requestFrame,
): void {
  setScrollTop(0);
  schedule(() => {
    setScrollTop(0);
    schedule(() => setScrollTop(0));
  });
}
