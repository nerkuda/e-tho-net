/**
 * Стек слоёв, которым принадлежит `Escape` поверх модальных диалогов
 * (ошибка 9ff6b606).
 *
 * **Проблема.** Каркас диалога (`lib/dialog.ts`) перехватывает `Escape` в
 * capture-фазе на `window` одним из первых. Меню, поповеры и выпадающие списки
 * открываются ПОЗЖЕ диалога, поэтому их capture-слушатели (и клавиатурные
 * контексты диспетчера `lib/keymap.ts`) срабатывают после диалогового: диалог
 * успевал закрыться (или позвать подтверждение несохранённых изменений) тем же
 * нажатием, которым закрывался верхний слой. Раньше это лечилось частной
 * проверкой `isMenuOpen()` в каркасе — она знала только про меню и не покрывала
 * ни поповеры, ни выпадашки подсказок.
 *
 * **Решение.** Верхний слой при открытии регистрирует себя в этом стеке, а
 * каркас диалога снимает снимок стека при показе ({@link escapeLayerSnapshot}):
 * если после снимка появился слой ({@link hasEscapeLayerAbove}), `Escape`
 * принадлежит ему — диалог то же нажатие не обрабатывает. Сам слой закрывается
 * своим механизмом: меню и выпадашка подсказок — capture-слушателем, поповер —
 * клавиатурным контекстом `ui-popover`, лупа — document-слушателем.
 *
 * Регистрировать слой обязаны только те слои, которые ГАРАНТИРОВАННО закрываются
 * по `Escape` (поповер с `closeOnEsc: false` — не регистрируется): иначе диалог
 * уступил бы нажатие слою, который его проигнорирует.
 *
 * Снимок, а не просто счётчик: слой, открытый ДО диалога (и оказавшийся под ним),
 * в снимок входит и на приоритет не влияет — даже если позже закроется.
 */

/** Токены открытых слоёв в порядке открытия. */
const layers: symbol[] = [];

/**
 * Регистрирует открытый слой; возвращает идемпотентное снятие. Вызывается при
 * открытии слоя и при его закрытии (любым путём — `Escape`, клик вне, выбор).
 */
export function pushEscapeLayer(): () => void {
  const token = Symbol('escape-layer');
  layers.push(token);
  let released = false;
  return () => {
    if (released) return;
    released = true;
    const index = layers.indexOf(token);
    if (index >= 0) layers.splice(index, 1);
  };
}

/** Снимок открытых слоёв — берётся в момент показа диалога. */
export function escapeLayerSnapshot(): readonly symbol[] {
  return [...layers];
}

/** Появился ли после снимка слой: `Escape` принадлежит верхнему слою, не диалогу. */
export function hasEscapeLayerAbove(snapshot: readonly symbol[]): boolean {
  return layers.some((token) => !snapshot.includes(token));
}

/** Тестовый слой: сброс состояния между сценариями. */
export const escapeLayerInternals = {
  reset(): void {
    layers.length = 0;
  },
  count(): number {
    return layers.length;
  },
};
