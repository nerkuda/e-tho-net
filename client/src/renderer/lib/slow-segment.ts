/**
 * Замер сегментов «горячих» путей рендерера (ошибка dc723634).
 *
 * Симптом, ради которого замер появился: фриз рендерера на ~15 с при двойном
 * клике по облачку. Сервер отвечал за 4 мс, а метка `ui.focus.applied` несла
 * `ms:15808` — значит время ушло ВНУТРИ клиента. Но какая именно нога цепочки
 * (`thoughts.focus` → история → публикация ответа → подписчики стора) его
 * заняла, журнал не показывал: виноватым одинаково выглядели и ожидание IPC, и
 * синхронная работа подписчиков.
 *
 * Замер закрывает эту дыру: сегмент дольше {@link SLOW_SEGMENT_MS} пишется
 * отдельной меткой `ui.slow_segment` с именем сегмента — следующий фриз сразу
 * называет виновника, а не оставляет «где-то между ответом сервера и
 * применением фокуса».
 *
 * Замер дешёвый (две отметки `performance.now`) и не влияет на
 * инструментируемый путь: медленный сегмент — это только строка журнала.
 */

import { logUiEvent } from './ui-log.js';

/** Порог «медленного» сегмента, мс: короче — нормальная работа пути. */
export const SLOW_SEGMENT_MS = 500;

/** Начало сегмента — пара к {@link measureSegment}. */
export function segmentStart(): number {
  return performance.now();
}

/**
 * Закрывает сегмент `name`, начатый в `startedAt`, и возвращает его
 * длительность в мс (её кладут в итоговую метку пути). Сегмент дольше порога
 * дополнительно пишется в журнал меткой `ui.slow_segment`: имя сегмента,
 * длительность и контекст вызова (`data`).
 */
export function measureSegment(
  name: string,
  startedAt: number,
  data?: Record<string, unknown>,
): number {
  const ms = Math.round(performance.now() - startedAt);
  if (ms >= SLOW_SEGMENT_MS) {
    logUiEvent('ui.slow_segment', { name, ms, ...data });
    // Медленный сегмент — диагностика для разработчика (не пользовательская
    // строка): в журнал он уже попал меткой, здесь — видимая причина в консоли.
    console.warn(`[ui] медленный сегмент ${name}: ${ms} мс`, data); // i18n: technical — диагностика разработчика
  }
  return ms;
}
