/**
 * Канал «значения свойств открытой карточки перечитать» (ошибка ec5ba58c).
 *
 * Значения показываются снимком, прочитанным при построении таблицы свойств, и
 * сам снимок от правок не обновляется. Меняться он может тремя путями:
 *
 *  - **своя правка из редактора свойств** — `editor/value-editor.ts` (значение
 *    свойства-связи, `crossResolve` снапшота имени). Своё событие приходит
 *    асинхронно (B1), поэтому производитель шлёт канал сам — мгновенный отклик;
 *  - **своя правка с карты** — диалог добавления, перетаскивание облачка,
 *    создание связи эллипсом (`canvas/*`, `editor/properties.ts`). Ребро в
 *    окрестности фокуса появилось, а таблица свойств фокусной мысли об этом не
 *    узнала бы: правка ребра не поднимает версию мысли, и гейт полной пересборки
 *    редактора не срабатывает;
 *  - **realtime** — `property-value.*`/`link.*` от другого клиента или MCP.
 *
 * Слушатель — таблица свойств (`editor/properties.ts`): событие документа, а не
 * прямой вызов, потому что производители (холст) не должны зависеть от
 * редактора — иначе получается цикл модулей холст → редактор → realtime-ui →
 * холст.
 */

/** Имя DOM-события «перечитать значения свойств». */
export const PROPERTY_VALUES_REFRESHED_EVENT = 'etn:property-values-refreshed';

/** Полезная нагрузка события. */
export interface PropertyValuesRefreshedDetail {
  /** Ключ свойства, если производитель знает его; `''` — «перечитать всё». */
  key: string;
}

/**
 * Просит открытую карточку прочитать значения свойств заново. `key` — ключ
 * свойства, которое правил производитель (`''`, когда правка затронула набор
 * значений целиком либо ключ неизвестен — холст знает лишь, что изменилась
 * окрестность фокуса).
 *
 * Вне DOM (юнит-тесты) вызов — no-op: глобалы `document`/`CustomEvent` там не
 * заведены, а проверять нечего.
 */
export function notifyPropertyValuesRefreshed(key = ''): void {
  if (typeof document === 'undefined' || typeof document.dispatchEvent !== 'function') return;
  if (typeof CustomEvent !== 'function') return;
  document.dispatchEvent(
    new CustomEvent<PropertyValuesRefreshedDetail>(PROPERTY_VALUES_REFRESHED_EVENT, {
      detail: { key },
    }),
  );
}
