/**
 * Якорь возврата клавиатурного фокуса (`data-focus-anchor`) — единый атрибут
 * для ВСЕХ списков дизайн-системы (правило 10 требования 11ddd910 «Единые
 * правила диалогов-списков», ошибка 28d69bc6).
 *
 * После закрытия диалога, открытого над списком (редактор строки, пикер),
 * каркас `lib/dialog.ts` возвращает фокус списку — иначе подсвеченная строка
 * остаётся, а стрелочная навигация не работает без повторного клика. Якорь —
 * устойчивый контейнер навигации списка: он переживает перерисовку строк и
 * владеет `keydown`.
 *
 * Модуль без зависимостей специально, чтобы атрибут объявлялся в одном месте и
 * его получали ОБА фасада списков — дерево (`./tree.ts`) и таблица
 * (`./table.ts`); каркас диалога (`../dialog.ts`) читает его отсюда. Разные
 * имена/дубли атрибута привели бы к тому, что один из фасадов молча выпадал из
 * механизма (так и было: якорь был только у дерева, таблицы фокус не
 * возвращали).
 */

/** Имя атрибута-метки корня списка: контейнер клавиатурной навигации. */
export const FOCUS_ANCHOR_ATTR = 'data-focus-anchor';

/** Селектор якоря фокуса. */
export const FOCUS_ANCHOR_SELECTOR = `[${FOCUS_ANCHOR_ATTR}]`;
