/**
 * Открытие цели строки-дневниковой записи — ОДНО решение для всех поверхностей
 * (0.15.4, тех.проект 43329662, требование ce121e09, сценарии 55c7f9c7,
 * eeffbc16, b87fb958).
 *
 * **Зачем модуль.** Правило «куда ведёт клик по строке-записи» сначала жило в
 * поиске (`search/search.ts::openRecordTarget`) и понадобилось вкладке
 * «Упоминания» (задача ae72e47e). Вторая копия неизбежно разошлась бы — ровно
 * так же, как расходились предикаты видимости привязок (стандарт a2488f05,
 * сторож `guard-record-row`), поэтому решение вынесено в `lib/`.
 *
 * **Правило.**
 *  * привязка-МЫСЛЬ — редактор мысли с активной вкладкой «Дневник» и выбранной
 *    строкой записи, затем фокус холста на ОТКРЫВАЕМУЮ привязку (адресат
 *    меняется с владельца записи на привязку). Порядок важен: программный вход
 *    `openRecordInEditor` ставит отложенный выбор записи, а его force-ветка при
 *    цели, равной текущему фокусу, за фокусом НЕ идёт — поэтому фокус ставит
 *    вызывающая сторона ОТДЕЛЬНО, после входа;
 *  * привязка-СВЯЗЬ — редактор связи БЕЗ записи (у редактора связи нет вкладки
 *    «Дневник», решение пользователя 2026-11-10); фокус не трогается;
 *  * владелец записи приходит сюда же при нуле видимых привязок (владелец-связь
 *    → редактор связи без записи).
 *
 * **Отказы.** Stale-цель (404/неразрешённая) — тихий пропуск, любой другой
 * отказ (сеть, сервер) — видимое сообщение: клик не должен выглядеть
 * «зависшим» (ошибка 53d21e82). Политику сообщения задаёт потребитель
 * ({@link RecordOpenActions.onFailure}); по умолчанию — тишина, чтобы `lib/` не
 * тянул словарь и тосты экрана.
 *
 * Модуль не импортирует `app.js` и экранные модули: сеть и действия приходят
 * параметром (`networkId` + {@link RecordOpenActions}) — циклов импорта нет.
 */

import type { Link } from '@etn/shared';

import type { RecordTargetRef } from './record-targets.js';

/** Действия и контекст открытия цели строки-записи. */
export interface RecordOpenActions {
  /** Сеть цели: связь запрашивается в ней. */
  networkId: string;
  /** Загрузить связь по id; 404 — цель удалили после запроса (stale). */
  getLink(networkId: string, linkId: string): Promise<Link>;
  /** Открыть редактор связи (без записи). */
  openLinkInEditor(link: Link): void;
  /** Открыть запись в редакторе мысли (вкладка «Дневник», выбранная строка). */
  openRecordInEditor(thoughtId: string, commentId: string): void;
  /** Фокус холста на мысль; отказы обрабатывает сам (тост внутри). */
  focusFromUi(thoughtId: string): Promise<void>;
  /** Отказ открытия: stale — тишина, прочее — сообщение. По умолчанию тишина. */
  onFailure?: (error: unknown) => void;
}

/**
 * Открывает цель строки-записи: мысль — редактор с записью и фокус на привязке,
 * связь — редактор связи без записи.
 */
export async function openRecordTarget(
  target: RecordTargetRef,
  commentId: string,
  actions: RecordOpenActions,
): Promise<void> {
  if (target.kind === 'link') {
    try {
      const link = await actions.getLink(actions.networkId, target.id);
      actions.openLinkInEditor(link);
    } catch (error) {
      actions.onFailure?.(error);
    }
    return;
  }
  // Порядок: вход, затем фокус — см. шапку модуля (force-ветка входа за
  // фокусом не следует).
  actions.openRecordInEditor(target.id, commentId);
  await actions.focusFromUi(target.id);
}
