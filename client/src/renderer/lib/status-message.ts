/**
 * Зона сообщений статусной строки — рутинные подтверждения клиента.
 *
 * Решение заказчика 2026-10-25 (задача 28d22b8a): всплывающие тосты оставлены
 * только для действительно важной информации, влияющей на работу клиента
 * (доступность сервера, ошибки соединения, потеря данных). Рутинные
 * подтверждения («комментарий записан», «скопировано», «сохранено») идут
 * сюда — в правую часть нижней статусной панели, справа от индикации сервера.
 *
 * Свойства зоны:
 * - **Одно сообщение.** Новое заменяет предыдущее (не накапливается): строка
 *   статус-бара одна, очередь сообщений читалась бы как шум.
 * - **TTL** — {@link STATUS_MESSAGE_TTL_MS}: сообщение не мигает и не висит
 *   вечно; по истечении текст гаснет.
 * - **Не теряет сообщения.** Пока статус-бар не смонтирован (старт клиента,
 *   экран без рабочего стола), последнее сообщение запоминается и
 *   показывается при монтировании ({@link mountStatusMessage}).
 *
 * Текст даёт вызывающий (из словаря `t()`); модуль лишь владеет местом, TTL и
 * заменой. Важные сообщения сюда НЕ попадают — их канал `notice`
 * (`lib/notice.ts`, тосты).
 */

/** Сколько сообщение живёт в статусной строке, мс: заметно, но не вечно. */
export const STATUS_MESSAGE_TTL_MS = 6_000;

/**
 * Минимальная форма узла зоны: текст и всплывающая подсказка. Структурный тип
 * (а не `HTMLElement`) — модуль не владеет разметкой и тестируется на шиме.
 */
export interface StatusMessageHost {
  textContent: string;
  title: string;
}

/** Узел зоны в статусной строке; `null` — статус-бар не смонтирован. */
let host: StatusMessageHost | null = null;

/** Таймер гашения текущего сообщения. */
let timer: number | null = null;

/** Сообщение, пришедшее до монтирования статус-бара (показывается при нём). */
let pending: string | null = null;

function clearTimer(): void {
  if (timer === null) return;
  window.clearTimeout(timer);
  timer = null;
}

/** Гасит текст зоны и отменяет таймер (сам узел остаётся смонтированным). */
function clearText(): void {
  clearTimer();
  if (host === null) return;
  host.textContent = '';
  host.title = '';
}

/**
 * Показывает рутинное сообщение в зоне статусной строки. Предыдущее
 * сообщение заменяется, таймер перезапускается. Пустой текст гасит зону.
 *
 * До монтирования статус-бара сообщение запоминается (последнее) и будет
 * показано при {@link mountStatusMessage} — молча сообщения не теряются.
 */
export function statusMessage(text: string): void {
  if (text.trim() === '') {
    pending = null;
    clearText();
    return;
  }
  if (host === null) {
    pending = text;
    return;
  }
  host.textContent = text;
  // Полный текст — в подсказке: в узком статус-баре строка обрезается
  // многоточием, но остаётся читаемой наведением.
  host.title = text;
  clearTimer();
  timer = window.setTimeout(() => {
    timer = null;
    clearText();
  }, STATUS_MESSAGE_TTL_MS);
}

/**
 * Подключает узел зоны сообщений (статусная строка рабочего стола). Если до
 * монтирования пришло сообщение — оно показывается сразу.
 */
export function mountStatusMessage(target: StatusMessageHost): void {
  host = target;
  host.textContent = '';
  host.title = '';
  clearTimer();
  const text = pending;
  pending = null;
  if (text !== null) statusMessage(text);
}

/**
 * Отключает зону от статус-бара (снятие рабочего стола): текст и таймер
 * сбрасываются. Сообщение, пришедшее ПОСЛЕ отключения, снова копится в
 * `pending` и покажется на следующем монтировании.
 */
export function unmountStatusMessage(): void {
  clearText();
  clearTimer();
  host = null;
  pending = null;
}
