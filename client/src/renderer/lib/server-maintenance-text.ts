/**
 * Текст состояния «сервер обновляется» (задача 479e37ed, требование 9636b1cc;
 * сценарий 610169a5).
 *
 * **Зачем отдельный модуль.** Одна и та же фраза нужна в трёх местах: строка
 * статус-бара (подсказка индикатора), уведомление при потере связи и тост в
 * момент входа в обслуживание. Дублировать формулировку по вызывающим нельзя —
 * это нарушает требование локализации (строки только из словаря `t()`) и
 * расходится при первой правке текста. Модуль чистый: ни DOM, ни store, ни
 * сети — только подстановка `retry_after` в ключ словаря.
 *
 * **Почему не в `status-message.ts`.** Тот модуль владеет местом и TTL зоны
 * сообщений, а не текстами состояния связи (свойства зоны описаны в
 * элементе «Статус-бар»). Здесь — ровно одна функция текста.
 */

import type { ServerMaintenanceDto } from '../../main/ipc/contract.js';
import { t } from './i18n.js';

/**
 * Фраза об обслуживании сервера: «Сервер обновляется, вернётся примерно через
 * N с». `null` — обслуживания нет (текст не нужен).
 *
 * Без `retry_after` (сервер/кадр его не сообщил) — та же мысль без срока: не
 * выдумывать число, которое не подтверждено.
 */
export function serverMaintenanceText(info: ServerMaintenanceDto | null): string | null {
  if (info === null || info.active !== true) return null;
  const retry = info.retry_after;
  // Нечисловой/нулевой срок — всё равно «срок неизвестен»: число в тексте
  // обязано быть подтверждено сервером (нормализация дублируется на границе
  // IPC, здесь — защита чистого помощника от прямых вызовов).
  return typeof retry === 'number' && Number.isFinite(retry) && retry > 0
    ? t('realtime.maintenance.waiting', Math.ceil(retry))
    : t('realtime.maintenance.noRetry');
}
