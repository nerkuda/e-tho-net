/**
 * Источник полёта при смене фокуса ВНЕ карты (дефект приёмки задачи e9f0af94).
 *
 * Когда фокус меняется по клику на облачко панели закреплённых, истории или
 * строки поиска, клон выбранной мысли должен вылетать «со стороны клика» — от
 * экранных координат кликнутого элемента, а не из слота на карте (которого у
 * невидимой на карте мысли просто нет). Координаты снимаются В МОМЕНТ клика:
 * рендер наступает после асинхронного `setFocus`, и к тому времени панель
 * могла перерисоваться, а элемент — потерять раскладку.
 *
 * Общий механизм один на все внешние точки смены фокуса: клик по облачку
 * регистрируется в общей фабрике жестов (`lib/thought-cloud.ts`), а карта
 * забирает координаты при отрисовке нового фокуса. Клики внутри холста
 * игнорируются — у мысли на карте уже есть собственный слот, и внешний
 * источник не должен его подменять.
 *
 * Хранится один «ожидающий» источник: клики последовательны, а `take`
 * очищает его независимо от совпадения id — чужой источник не должен
 * протечь в следующую смену фокуса.
 */

import type { RectLike } from './pure.js';

/** Ожидающий источник полёта: id мысли и её экранный прямоугольник (или null). */
let pending: { id: string; rect: RectLike | null } | null = null;

/** Экранный прямоугольник элемента; `null`, если у него нет раскладки. */
function elementRect(el: Element | null): RectLike | null {
  if (el === null) return null;
  const r = el.getBoundingClientRect();
  if (r.width <= 0 || r.height <= 0) return null;
  return { left: r.left, top: r.top, width: r.width, height: r.height };
}

/**
 * Запоминает кликнутый элемент как источник следующего полёта к мысли `id`.
 * Элементы внутри холста (`.canvas`) пропускаются: у облачка на карте
 * стартовый слот известен из раскладки, и подменять его нечем.
 */
export function noteFocusOrigin(id: string, el: Element | null): void {
  if (el !== null && el.closest('.canvas') !== null) return;
  pending = { id, rect: elementRect(el) };
}

/**
 * Забирает ожидающий источник для мысли `id` (и всегда очищает хранилище).
 * Возвращает прямоугольник или `null`, если источника для этой мысли не было
 * либо у элемента не оказалось раскладки — тогда полёт деградирует мягко.
 */
export function takeFocusOrigin(id: string): RectLike | null {
  const current = pending;
  pending = null;
  return current !== null && current.id === id ? current.rect : null;
}

/** Сбрасывает ожидающий источник (тесты, смена вкладки/сети). */
export function clearFocusOrigin(): void {
  pending = null;
}
