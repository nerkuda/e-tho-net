/**
 * Хелпер «мы в Основе?» — единая проверка для блокировки правок онтологии
 * (отборы типов мыслей и др.) в слоях изменений (задача d9b66617).
 *
 * Отборы типов мыслей — сервисный инструмент общего пользования, а не
 * предмет «песочниц»/защиты от неполных данных: их правка в слое изменений
 * запрещена. Истину о слое хранит `store.state.currentLayer`:
 *   - `null` — слой ещё не выбран (свежеоткрытая сеть);
 *   - `{ id: BASE_LAYER_ID, title: 'Основа' }` — пользователь в Основе;
 *   - любой другой id — пользователь в одном из слоёв изменений.
 *
 * Полный список слоёв с флагом `is_base` живёт в `store.state.layers`, но
 * для UX-проверки достаточно сопоставить id с константой `BASE_LAYER_ID` —
 * она стабильна и обновляется только вместе с миграциями сети.
 */

import { BASE_LAYER_ID } from '@etn/shared';

import { store } from '../state.js';

/**
 * `true`, когда активная сессия работает в Основе сети:
 * слой не выбран или выбран базовый слой.
 */
export function isInBaseLayer(): boolean {
  const current = store.state.currentLayer;
  return current === null || current.id === BASE_LAYER_ID;
}
