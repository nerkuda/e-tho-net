/**
 * Полный разбор CodeMirror 6 в headless-тестах редактора (задача `f9b5c36e`).
 *
 * **Почему это нужно.** Клиентские тесты строят настоящий `EditorState` без
 * `EditorView`. Начальный разбор делает `@codemirror/language`
 * (`LanguageState.init`) с ДВУМЯ ограничениями: бюджет времени 20 мс
 * (`Work.Apply`) и обрезка по вьюпорту 3000 символов (`Work.InitViewport`).
 * Доразбор в редакторе ведёт `parseWorker`, а это ViewPlugin — без view дерево
 * не достраивается уже никогда, `syntaxTree(state)` остаётся обрезанным.
 *
 * Отсюда флейк «под нагрузкой» (задача `f9b5c36e`, ранее `c543ea79`): если
 * процесс вытеснен планировщиком дольше 20 мс прямо посреди начального разбора,
 * бюджет истекает и дерево усекается. Тест, читающий производное от дерева
 * состояние (`commentCollapseInternals.collectSections`, поле `livePreview`,
 * поле-гаттер сворачивания), видит меньше узлов и падает. В изоляции (без
 * конкуренции за CPU) 20 мс не истекают — флейк не воспроизводится. Протечка
 * модульного состояния тут ни при чём: `node --test` исполняет каждый файл в
 * отдельном процессе.
 *
 * На документе длиннее 3000 символов дерево обрезано ВСЕГДА — обрезка по
 * вьюпорту не гонка, а дизайн; без view полное дерево для такого документа
 * недостижимо (та же обрезка в клиенте — ошибка `8c890ee7` о разметке длинных
 * комментариев).
 *
 * **Что делает.** {@link createParsedState} создаёт состояние и ПРОВЕРЯЕТ, что
 * дерево полное с самого создания (`syntaxTreeAvailable`). Если бюджет
 * разбора всё-таки истёк — состояние создаётся заново (разбор идёт с нуля,
 * вытеснение процесса к следующей попытке проходит). Проверка при создании, а
 * не «доведение» после — принципиально: поля, производные от дерева
 * (`livePreview`, поле сворачивания), ленивые и вычисляются при первом чтении,
 * то есть уже по полному дереву состояния. Доведение разбора после создания
 * их значение не перестроит.
 *
 * Сторож правила — `guard-editor-parse-complete.test.ts`.
 */

import { syntaxTreeAvailable } from '@codemirror/language';
import type { EditorState } from '@codemirror/state';

/**
 * Потолок длины документа для headless-теста: вьюпорт начального разбора
 * (`Work.InitViewport` в `@codemirror/language`).
 */
export const MAX_HEADLESS_PARSE_LENGTH = 3000;

/**
 * Сколько раз пересоздавать состояние, если очередная попытка разбора попала
 * под вытеснение процесса. Разбор тестового документа занимает микросекунды —
 * промахнуться всеми попытками подряд практически невозможно, а если это
 * случилось, лучше громкая ошибка, чем молча прочитанное обрезанное дерево.
 */
export const PARSE_ATTEMPTS = 10;

/**
 * Создаёт состояние с ПОЛНЫМ деревом разбора: передайте фабрику
 * (`() => EditorState.create({...})`) и используйте возвращённое состояние
 * вместо исходного. Фабрика вызывается столько раз, сколько нужно попыток.
 *
 * Бросает исключение, если документ длиннее {@link MAX_HEADLESS_PARSE_LENGTH}
 * (полное дерево в headless-режиме недостижимо) или если разбор так и не
 * удался: молча прочитанное обрезанное дерево и есть тот самый флейк.
 */
export function createParsedState(create: () => EditorState): EditorState {
  let last: EditorState | null = null;
  for (let attempt = 0; attempt < PARSE_ATTEMPTS; attempt += 1) {
    const state = create();
    if (state.doc.length > MAX_HEADLESS_PARSE_LENGTH) {
      throw new Error(
        `CodeMirror headless: документ длиной ${state.doc.length} символов — начальный разбор ` +
          `обрезан по вьюпорту ${MAX_HEADLESS_PARSE_LENGTH} символов, а доразбора без EditorView ` +
          'не существует. Уменьшите документ теста либо проверяйте длинный документ иначе ' +
          '(tests/editor-parse.ts).',
      );
    }
    if (syntaxTreeAvailable(state, state.doc.length)) return state;
    last = state;
  }
  throw new Error(
    `CodeMirror: разбор документа (${last?.doc.length} символов) не доведён до конца за ` +
      `${PARSE_ATTEMPTS} попыток — тест читал бы обрезанное дерево. Это источник флейка под ` +
      'нагрузкой, см. tests/editor-parse.ts.',
  );
}
