/**
 * Файлы пользователя серверного уровня (таблица `user_files` в `_system.db`,
 * сущность 62fd29b5, ADR a5888535): файл живёт на уровне «пользователь ×
 * сервер», вне сетей, и не является вложением (у вложений мульти-владение и
 * лимит 10 МиБ). Сейчас единственный вид — фоновая картинка карты
 * (`map_wallpaper`, операция 31ef478a); набор видов расширяемый.
 */

import type { UserFileKind } from '../constants.js';

/**
 * Метаданные картинки, вычисленные КЛИЕНТОМ до отправки (ADR a5888535):
 * сервер не получает image-зависимостей и хранит значения как есть.
 */
export interface WallpaperMeta {
  /** Ширина после клиентского даунскейла, px (> 0). */
  width: number;
  /** Высота после клиентского даунскейла, px (> 0). */
  height: number;
  /** Средняя светлота 0..1 — база для алгоритмов контраста на карте. */
  avg_luminance: number;
  /**
   * Доминирующий тон 0..360 (необязателен: клиент может не считать).
   * `null` допустим: сервер хранит `meta` как есть (сущность 62fd29b5).
   */
  dominant_hue?: number | null;
  /** Насыщенность доминирующего тона 0..1 (необязательна; `null` допустим). */
  dominant_sat?: number | null;
}

/**
 * `GET /api/v1/users/me/wallpaper` — метаданные текущей фоновой картинки
 * пользователя (операция 31ef478a). `url` — относительный путь байтов на этом
 * же сервере (`…/wallpaper/raw`), чтобы клиент не собирал его из частей.
 */
export interface WallpaperInfo {
  kind: UserFileKind;
  mime_type: string;
  file_size: number;
  meta: WallpaperMeta;
  url: string;
}
