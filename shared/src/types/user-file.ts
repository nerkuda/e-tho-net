/**
 * Файлы пользователя серверного уровня в сети (таблица `user_files` в
 * `_system.db`, сущность 62fd29b5, ADR a5888535): файл живёт на уровне
 * «пользователь × сеть × вид» и не является вложением (у вложений
 * мульти-владение и лимит 10 МиБ). Сейчас единственный вид — фоновая картинка
 * карты (`map_wallpaper`, операция 31ef478a); набор видов расширяемый.
 * Картинка своя в каждой сети (ревизия 2026-11-13, задача 5db41abf).
 */

import type { UserFileKind } from '../constants.js';

/**
 * Метаданные картинки, вычисленные КЛИЕНТОМ до отправки (ADR a5888535):
 * сервер не получает image-зависимостей и хранит значения как есть.
 */
export interface WallpaperMeta {
  /** Ширина после клиентского даунскейла, px (> 0). */
  width: number;
  /** Высота после клиентского даунскейла, px (> 0). */
  height: number;
  /** Средняя светлота 0..1 — база для алгоритмов контраста на карте. */
  avg_luminance: number;
  /**
   * Доминирующий тон 0..360 (необязателен: клиент может не считать).
   * `null` допустим: сервер хранит `meta` как есть (сущность 62fd29b5).
   */
  dominant_hue?: number | null;
  /** Насыщенность доминирующего тона 0..1 (необязательна; `null` допустим). */
  dominant_sat?: number | null;
}

/**
 * `GET /api/v1/users/me/wallpaper?network_id=…` — метаданные фоновой картинки
 * пользователя в заданной сети (операция 31ef478a). `url` — относительный путь
 * байтов ЭТОЙ сети на этом же сервере (готовый, с `?network_id=…`): без
 * параметра ссылка нерабочая, поэтому клиенту не нужно собирать её из частей.
 * `network_id` возвращается отдельным полем, чтобы клиент проверил, что ответ
 * относится к запрошенной сети.
 */
export interface WallpaperInfo {
  kind: UserFileKind;
  /** Сеть, в которой пользователь выбрал эту картинку (ревизия 2026-11-13). */
  network_id: string;
  mime_type: string;
  file_size: number;
  meta: WallpaperMeta;
  url: string;
}
