/**
 * «Связи дня» — DTO блока дня ленты «Дневника» (0.16.1, задача «0.16.1: связи
 * дня и открытые дела»; требование `1fb1047d`, элемент интерфейса `8ecc30cd`).
 *
 * Блок собирает всё, что относится к дате, КРОМЕ записей и задач (они показаны
 * своими местами — дублирование запрещено):
 *   * датовые факты — значения-даты свойств мыслей (`property_values` +
 *     справочник `properties`);
 *   * date-ссылки `[[YYYY-MM-DD[ HH:MM]]]` из строк ХРОНО-записей и ПОСТОЯННЫХ
 *     комментариев, взятые из материализованной проекции задач (`task_row_dates`,
 *     INDEX(date), ADR `d0c07f33`) — парсинг на лету не выполняется.
 *
 * Строки-задачи (`task_rows.is_task = 1`) в состав блока не входят: их даты
 * показывает панель «Задачи» (элемент `f3893859`) и «Задачи периода».
 *
 * Дата — календарный день `YYYY-MM-DD`: сутки наблюдателя считает клиент
 * (решение «локальные сутки просматривающего клиента»), сервер хранит и отдаёт
 * календарные дни date-ссылок как есть, а интервалы записей-источников — как
 * UTC-инстансы, чтобы клиент сам решил, попадает ли источник в этот день.
 */

import type { CommentKind } from '../enums.js';
import type { CommentOwnerKind } from './comment.js';

/** Датовый факт: значение-дата свойства мысли (`YYYY-MM-DD`). */
export interface DayFact {
  /** Календарный день факта (`YYYY-MM-DD`) — день запроса. */
  day: string;
  /** Мысль-владелец значения. */
  thought_id: string;
  /** Название мысли на момент чтения (для подписи и сортировки по алфавиту). */
  title: string;
  /** Свойство-дата справочника. */
  property_id: string;
  /** Имя свойства (подпись факта). */
  property_name: string;
  /** Значение-дата как хранится (`YYYY-MM-DD` или ISO-инстанс). */
  value: string;
}

/**
 * Источник date-ссылки: строка комментария (номер с нуля) и его владелец.
 *
 * Владелец нужен клиенту для клика «сниппет → источник»: у постоянного
 * комментария это карточка владельца (мысль/связь/публикация), у хроно-записи —
 * сама запись (`valid_from`/`valid_to`).
 */
export interface DayLinkSource {
  comment_id: string;
  /** Номер строки `body_md` с нуля (адрес строки проекции). */
  line_no: number;
  /** Снапшот строки без маркера задачи (текст сниппета). */
  text: string;
  /** Вид комментария-источника. */
  kind: CommentKind;
  owner_type: CommentOwnerKind;
  owner_id: string;
  /** Название владельца комментария для облачка источника. */
  owner_title: string;
  /** Начало записи-источника (UTC-инстанс); у постоянного комментария — `null`. */
  source_from: string | null;
  /** Конец записи-источника (UTC-инстанс); у постоянного комментария — `null`. */
  source_to: string | null;
  /** Заголовок записи-источника (у постоянного комментария — `null`). */
  source_title: string | null;
}

/** Date-ссылка строки комментария, указывающая на день. */
export interface DayLink {
  /** День, на который указывает ссылка (`YYYY-MM-DD`). */
  day: string;
  /** Время цели ссылки (`HH:MM`), `null` — цель без времени. */
  time: string | null;
  source: DayLinkSource;
}

/** Ответ выборки «связей дня» за период (GET /chronicle/day-links). */
export interface DayLinksResult {
  /** Датовые факты мыслей за запрошенный период. */
  facts: DayFact[];
  /** Date-ссылки за запрошенный период (без строк задач). */
  links: DayLink[];
}
