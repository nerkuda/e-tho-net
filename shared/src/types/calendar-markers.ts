/**
 * Маркеры дней календаря месяца «Дневника» (0.16.1, задача `d793fd69`;
 * требование `ab9d627b`, элемент интерфейса `55b07702`).
 *
 * Клетка календаря несёт до четырёх маркеров-цветов, каждый на своём
 * фиксированном месте:
 *   * `records` — дни с хроно-записями (запись отмечает все дни своего
 *     интервала `valid_from…valid_to`);
 *   * `plans` — задачи и напоминания: задача отмечает ВСЕ даты своего периода
 *     (`task_rows.period_from…period_to`), напоминание — все дни раскрытых
 *     за месяц вхождений серии;
 *   * `facts` — датовые факты мыслей и date-ссылки не-задачных строк;
 *   * `overdue` — просрочка: незакрытая задача со сроком (`due`) раньше
 *     «сегодня» клиента; отмечается день срока.
 *
 * Счётчиков в клетках нет (число-счётчик и точки-пороги 0.10.2 упразднены).
 *
 * **Сутки считает клиент.** Сервер не хранит часовой пояс и не решает, какой
 * сейчас день (требование `fcdcd75f`): задачи и датовые факты лежат в
 * календарных днях и отдаются днями, а интервалы записей и моменты вхождений
 * напоминаний — UTC-инстансами, которые клиент раскладывает по СВОИМ локальным
 * суткам. «Сегодня» для просрочки приходит от клиента (`today`).
 */

/** Вид маркера дня календаря. */
export type CalendarMarkerKind = 'records' | 'plans' | 'facts' | 'overdue';

/**
 * Порядок маркеров в клетке календаря — ФИКСИРОВАННЫЕ места (требование
 * ab9d627b): записи, задачи и напоминания, датовые факты и date-ссылки,
 * просрочка. Одна точка правды для группировки ответа (экран «Дневник») и
 * отрисовки (`lib/month-calendar.ts`).
 */
export const CALENDAR_MARKER_ORDER: readonly CalendarMarkerKind[] = [
  'records',
  'plans',
  'facts',
  'overdue',
];

/** Интервал хроно-записи (UTC-инстансы); `to` — `null` у записи одного момента. */
export interface CalendarRecordSpan {
  /** Начало записи (UTC-инстанс). */
  from: string;
  /** Конец записи (UTC-инстанс); `null` — запись без окончания/одного момента. */
  to: string | null;
}

/**
 * Ответ выборки маркеров за календарный месяц
 * (`GET /chronicle/calendar-markers`).
 *
 * Сервер расширяет окно поиска записей и напоминаний на сутки в обе стороны
 * (`from − 1` … `to + 1` по UTC) — это поисковое окно, а не «сутки
 * наблюдателя»: клиент отбрасывает дни вне своего месяца, поэтому запись или
 * вхождение у локальной полуночи не теряется при любом поясе.
 */
export interface CalendarMarkersResult {
  /** Интервалы хроно-записей, пересёкших поисковое окно. */
  record_spans: CalendarRecordSpan[];
  /** Календарные дни периодов задач (все даты периода внутри месяца). */
  task_days: string[];
  /** Дни-сроки незакрытых задач со сроком раньше `today` (просрочка). */
  overdue_days: string[];
  /** Календарные дни датовых фактов мыслей и date-ссылок не-задачных строк. */
  fact_days: string[];
  /** Моменты вхождений напоминаний запросившего пользователя (UTC-инстансы). */
  reminder_instants: string[];
}
