/**
 * DTO статистики мыслесети (задача c69b078d, версия 0.9.1,
 * `GET /networks/{nid}/statistics`).
 *
 * Диалог «Статистика мыслесети» показывает объём данных сети. Числа — сумма
 * по ВСЕМ слоям сети: слои задают область данных (copy-on-write ветки), и
 * отбор по сессионному слою здесь НЕ применяется, поэтому одна и та же
 * логическая сущность, перекрытая тенью слоя, учитывается в каждой физической
 * строке (это «объём хранения», а не «число видимых сущностей»).
 *
 * Для мыслей и связей есть разбивка по актуальности и корзине; у онтологии
 * (типы, свойства) и слоёв разбивок не существует — там только «всего».
 */

/** Разбивка счётчиков сущности с актуальностью и корзиной. */
export interface StatsBreakdown {
  /** Всего строк: `deleted = 0` во всех слоях. */
  total: number;
  /** Актуальные: не в корзине и `active = 1`. */
  active: number;
  /** Неактуальные: не в корзине и `active = 0`. */
  inactive: number;
  /** В корзине: `marked_for_deletion = 1` (среди неудалённых). */
  trashed: number;
}

/** Вложения сети (только чтение). */
export interface StatsAttachments {
  /** Всего вложений (ссылок и файловых), `deleted = 0`. */
  total: number;
  /** Из них файловых (`kind = 'file'`). */
  files: number;
  /**
   * Суммарный размер файловых вложений в байтах (`SUM(file_size)`).
   * Человекочитаемый вид (КБ/МБ/ГБ) строит клиент.
   */
  file_size_bytes: number;
}

/** Ответ `GET /networks/{nid}/statistics` — агрегат по всей мыслесети. */
export interface NetworkStats {
  /** Типов мыслей (онтология, без разбивки). */
  thought_types: number;
  /** Типов связей (онтология, без разбивки). */
  link_types: number;
  /** Свойств мыслей — реестр без системных структурных («Родители»/«Потомки»). */
  properties: number;
  /** Мысли: всего / актуальные / неактуальные / в корзине. */
  thoughts: StatsBreakdown;
  /** Связи: всего / актуальные / неактуальные / в корзине. */
  links: StatsBreakdown;
  /** Слои сети (основа + пользовательские; сервисные/резервные не считаются). */
  layers: number;
  /** Вложения. */
  attachments: StatsAttachments;
}
